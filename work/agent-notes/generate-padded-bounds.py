#!/usr/bin/env python3
"""Emit ordinary Lean proofs for every fixed padded section and their list.

No literal is reimplemented. Each section theorem imports the fixed declaration;
the program order/append tree is taken from the fixed metadata definition. This
generator is not trusted: Lean must check every emitted theorem. Importing the
metadata proof module itself would pull in unrelated FFI/shmem computation.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "submission/InitECandidate/Solver/LabBound"
FIXED = ROOT / "submission/InitECandidate/Proofs/BackendStages"
text = (FIXED / "Metadata/LiteralFacts.lean").read_text()
definition = re.search(r"^def paddedProgram : LabSem.LabProgHOL 64 := (.+)$", text, re.M)
assert definition
expression = definition[1]
groups = re.findall(r"\[([^\[\]]*)\]", expression)
ids = [int(n) for n in re.findall(r"\bPadded(\d+)\b", expression)]
assert ids == [0, 1, 2, 4, 5, 6] + list(range(64, 890))
assert len(ids) == len(set(ids)) == 832
dest = OUT / "Padded"
dest.mkdir(exist_ok=True)

def module(n):
    return {64: "InitECandidate.Solver.LabBound.PaddedPilot",
            713: "InitECandidate.Solver.LabBound.PaddedLarge"}.get(
                n, f"InitECandidate.Solver.LabBound.Padded.Section{n}")

for n in ids:
    assert (FIXED / f"Padded{n}.lean").is_file()
    if n in (64, 713):
        continue
    (dest / f"Section{n}.lean").write_text(f"""import InitECandidate.Solver.LabBound.CheckLayout
import InitECandidate.Proofs.BackendStages.Padded{n}

-- Generated by work/agent-notes/generate-padded-bounds.py.
namespace InitECandidate.Solver.LabBound
set_option maxRecDepth 1000000
set_option maxHeartbeats 0

theorem padded{n}_fits :
    sectionFits 24 InitECandidate.Proofs.BackendStages.Padded{n} = true := by
  decide

end InitECandidate.Solver.LabBound
#print axioms InitECandidate.Solver.LabBound.padded{n}_fits
""")

for i, group in enumerate(groups):
    members = [int(n) for n in re.findall(r"Padded(\d+)", group)]
    imports = "\n".join(f"import {module(n)}" for n in members)
    if not members:
        imports = "import InitECandidate.Solver.LabBound.CheckLayout"
    opened = "Flapjack.Compiler.Backend" + (" InitECandidate.Proofs.BackendStages" if members else "")
    facts = "".join(f"padded{n}_fits, " for n in members)
    (dest / f"Chunk{i}.lean").write_text(f"""{imports}

-- Generated by work/agent-notes/generate-padded-bounds.py.
namespace InitECandidate.Solver.LabBound
open {opened}

def paddedChunk{i} : LabSem.LabProgHOL 64 := [{group}]

theorem paddedChunk{i}_fits : paddedChunk{i}.all (sectionFits 24) = true := by
  simp only [paddedChunk{i}, List.all_cons, List.all_nil, {facts}Bool.and_self]

end InitECandidate.Solver.LabBound
#print axioms InitECandidate.Solver.LabBound.paddedChunk{i}_fits
""")

chunks = iter(range(len(groups)))
expression = re.sub(r"\[[^\[\]]*\]", lambda _: f"paddedChunk{next(chunks)}", expression)
imports = "\n".join(f"import InitECandidate.Solver.LabBound.Padded.Chunk{i}" for i in range(len(groups)))
facts = ",\n    ".join(f"paddedChunk{i}_fits" for i in range(len(groups)))
(OUT / "PaddedProgram.lean").write_text(f"""{imports}

/-! Layout facts for the fixed padded sections, in exactly the metadata's order.
This list avoids the unrelated FFI/shmem proofs imported by Metadata.LiteralFacts.
The generator copies its append tree; equality to that named metadata declaration
is left to the later artifact integration, not assumed by this theorem. -/
namespace InitECandidate.Solver.LabBound
open Flapjack.Compiler.Backend
set_option maxRecDepth 10000

def fixedPaddedProgram : LabSem.LabProgHOL 64 := {expression}

theorem fixedPaddedProgram_fits : fixedPaddedProgram.all (sectionFits 24) = true := by
  simp only [fixedPaddedProgram, List.all_append, {facts}, Bool.and_self]

theorem fixedPaddedProgram_layout :
    LineBound fixedPaddedProgram 24 ∧ NoInstall fixedPaddedProgram :=
  programFits_spec 24 fixedPaddedProgram fixedPaddedProgram_fits

end InitECandidate.Solver.LabBound
#print axioms InitECandidate.Solver.LabBound.fixedPaddedProgram_fits
#print axioms InitECandidate.Solver.LabBound.fixedPaddedProgram_layout
""")
print(f"Generated {len(ids) - 2} section proofs, {len(groups)} chunks and the program theorem")
