#!/usr/bin/env python3
"""Emit kernel-checked fixed Raw/Alloc syntax facts in 16-procedure chunks.

Read actual fixed chunk expressions; never reimplement program ASTs. The local
aggregate has the fixed stack's append tree. Its equality to the umbrella
Raw.stack/Alloc.stack declarations remains a separate integration obligation.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
fixed = root / 'submission/InitECandidate/Proofs/BackendStages'
out = root / 'submission/InitECandidate/Solver/StackStatic'
out.mkdir(exist_ok=True)
namespace = 'InitECandidate.Solver.StackStatic'
modules = {}
for identifier in range(64, 890):
    if identifier in (64, 713):
        modules[identifier] = 'InitECandidate.Solver.StackRemoveDirect.' + ('Pilot' if identifier == 64 else 'Large')
        continue
    modules[identifier] = f'{namespace}.Procedure{identifier}'
    (out / f'Procedure{identifier}.lean').write_text(f'''import InitECandidate.Solver.StackRemoveDirect.Safety
import InitECandidate.Solver.StackAllocBound.Safety
import InitECandidate.Proofs.BackendStages.Alloc{identifier}

-- Generated by work/agent-notes/generate-stack-static.py.
namespace InitECandidate.Solver.StackRemoveDirect
open InitECandidate.Proofs.BackendStages
set_option maxRecDepth 1000000
set_option maxHeartbeats 0

theorem raw{identifier}Eligible : InitECandidate.Solver.StackAllocBound.eligible raw{identifier} = true := by decide

theorem alloc{identifier}Supported : supported Alloc{identifier}.2 = true := by decide

end InitECandidate.Solver.StackRemoveDirect
#print axioms InitECandidate.Solver.StackRemoveDirect.raw{identifier}Eligible
#print axioms InitECandidate.Solver.StackRemoveDirect.alloc{identifier}Supported
''')
for index, start in enumerate(range(64, 890, 16)):
    end = min(start + 15, 889)
    ids = list(range(start, end + 1))
    expressions = {}
    for stage in ('Raw', 'Alloc'):
        src = (fixed / f'{stage}Chunk{start}_{end}.lean').read_text()
        match = re.search(r'^def bodies : [^\n]* := (.+)$', src, re.M)
        assert match, (stage, start)
        expr = match[1]
        names = re.findall(r'raw(\d+)' if stage == 'Raw' else r'Alloc(\d+)', expr)
        assert list(map(int, names)) == ids, (stage, start, names)
        expressions[stage] = expr
    imports = '\n'.join('import ' + modules[n] for n in ids)
    # List.all builds a right-associated conjunction, independent of Bool syntax precedence.
    raw_goal = ' && ('.join(f'InitECandidate.Solver.StackAllocBound.eligible raw{n}' for n in ids) + ' && true' + ')' * (len(ids) - 1)
    alloc_goal = ' && ('.join(f'supported Alloc{n}.2' for n in ids) + ' && true' + ')' * (len(ids) - 1)
    raw_facts = ', '.join(f'raw{n}Eligible' for n in ids)
    alloc_facts = ', '.join(f'alloc{n}Supported' for n in ids)
    (out / f'Chunk{index}.lean').write_text(f'''{imports}
import InitECandidate.Solver.StackRemoveDirect.CheckCode

-- Generated by work/agent-notes/generate-stack-static.py.
namespace {namespace}
open Flapjack Flapjack.Compiler.Backend.StackLang InitECandidate.Proofs.BackendStages
open InitECandidate.Solver.StackRemoveDirect
set_option maxRecDepth 100000
{chr(10).join(["set_option maxHeartbeats 0"] if index == 40 else [])}
def rawChunk{index} : List (Nat × HolProg 64) := {expressions['Raw']}
def allocChunk{index} : List (Nat × HolProg 64) := {expressions['Alloc']}

theorem rawChunk{index}Eligible :
    rawChunk{index}.all (fun entry => InitECandidate.Solver.StackAllocBound.eligible entry.2) = true := by
  change ({raw_goal}) = true
  simp only [{raw_facts}, Bool.true_and]

theorem allocChunk{index}Supported : entriesSafe allocChunk{index} = true := by
  change ({alloc_goal}) = true
  simp only [{alloc_facts}, Bool.true_and]

end {namespace}
#print axioms {namespace}.rawChunk{index}Eligible
#print axioms {namespace}.allocChunk{index}Supported
''')
imports = '\n'.join(f'import {namespace}.Chunk{i}' for i in range(52))
raw_expr = 'RawStubs ++ (' + ' ++ ('.join(f'rawChunk{i}' for i in range(52)) + ' ++ []' + ')' * 52
alloc_expr = 'AllocStubs ++ (' + ' ++ ('.join(f'allocChunk{i}' for i in range(52)) + ' ++ []' + ')' * 52
raw_facts = ', '.join(f'rawChunk{i}Eligible' for i in range(52))
alloc_facts = ', '.join(f'(show allocChunk{i}.all (fun entry => entry.1 == 6 || supported entry.2) = true from allocChunk{i}Supported)' for i in range(52))
(out / 'Programs.lean').write_text(f'''{imports}
import InitECandidate.Solver.StackAllocBound.RuntimeStubs
import InitECandidate.Solver.StackAllocBound.CheckCode

-- Generated by work/agent-notes/generate-stack-static.py. These local literal
-- lists still need their explicit equality to the fixed umbrella stack declarations.
namespace {namespace}
open Flapjack Flapjack.Compiler.Backend.StackLang InitECandidate.Proofs.BackendStages
open InitECandidate.Solver.StackRemoveDirect
set_option maxRecDepth 100000

def rawProgram : List (Nat × HolProg 64) := {raw_expr}
def allocProgram : List (Nat × HolProg 64) := {alloc_expr}

theorem rawProgramEligible :
    rawProgram.all (fun entry => InitECandidate.Solver.StackAllocBound.eligible entry.2) = true := by
  simp only [rawProgram, List.all_append, List.all_nil,
    InitECandidate.Solver.StackAllocBound.rawStubsEligible, {raw_facts}, Bool.and_true]

theorem allocProgramSupported : entriesSafe allocProgram = true := by
  simp only [entriesSafe, allocProgram, List.all_append, List.all_nil,
    allocStubsSupported, {alloc_facts}, Bool.and_true]

theorem rawCodeSafe : InitECandidate.Solver.StackAllocBound.CodeSafe (sptFromAList rawProgram) :=
  InitECandidate.Solver.StackAllocBound.list_codeSafe rawProgram rawProgramEligible

theorem allocCodeSafe : CodeSafe (sptFromAList allocProgram) :=
  entriesSafe_codeSafe allocProgram allocProgramSupported

end {namespace}
#print axioms {namespace}.rawProgramEligible
#print axioms {namespace}.allocProgramSupported
#print axioms {namespace}.rawCodeSafe
#print axioms {namespace}.allocCodeSafe
''')
print(f'Generated 824 procedure modules, 52 chunks and Programs under {out}')
