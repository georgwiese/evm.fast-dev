#!/usr/bin/env python3
"""Emit kernel cost/no-Install checks for the actual fixed optimized Word bodies.

The local aggregate still needs equality to the compiler's umbrella code list.
Generation and text coverage are not substitutes for successful Lean builds.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "submission/InitECandidate/Solver/WordStatic"
OUT.mkdir(exist_ok=True)
NS = "InitECandidate.Solver.WordStatic"
umbrella = (ROOT / "submission/InitECandidate/Proofs/StackAnalysis/Data.lean").read_text()
outputs = re.search(r"^def outputs := (.+)$", umbrella, re.M)
assert outputs and list(map(int, re.findall(r"optimized(\d+)", outputs[1]))) == list(range(64, 890))
modules = {}
for identifier in range(64, 890):
    literal = ROOT / f"submission/InitECandidate/Proofs/StackAnalysis/Data{identifier}.lean"
    assert literal.is_file(), literal
    if identifier in (66, 713):
        modules[identifier] = "InitECandidate.Solver.WordToStackBound.Pilot"
        continue
    modules[identifier] = f"{NS}.Procedure{identifier}"
    (OUT / f"Procedure{identifier}.lean").write_text(f'''import InitECandidate.Solver.WordToStackBound.Cost
import InitECandidate.Proofs.StackAnalysis.Data{identifier}

-- Generated by work/agent-notes/generate-word-static.py.
namespace InitECandidate.Solver.WordToStackBound
open Flapjack InitECandidate.Proofs.StackAnalysis
set_option maxRecDepth 1000000
set_option maxHeartbeats 0

theorem ceiling{identifier} : ceiling optimized{identifier}.2.2 ≤ 4 := by decide
theorem noInstall{identifier} : noInstallSubprogsHOL optimized{identifier}.2.2 = true := by decide

end InitECandidate.Solver.WordToStackBound
#print axioms InitECandidate.Solver.WordToStackBound.ceiling{identifier}
#print axioms InitECandidate.Solver.WordToStackBound.noInstall{identifier}
''')
for index, start in enumerate(range(64, 890, 16)):
    ids = list(range(start, min(start + 16, 890)))
    imports = "\n".join("import " + modules[n] for n in ids)
    entries = ", ".join(f"optimized{n}" for n in ids)
    terms = [f"(noInstallSubprogsHOL optimized{n}.2.2 && decide (ceiling optimized{n}.2.2 ≤ 4))" for n in ids]
    goal = " && (".join(terms) + " && true" + ")" * (len(ids) - 1)
    facts = ", ".join(f"noInstall{n}, ceiling{n}" for n in ids)
    (OUT / f"Chunk{index}.lean").write_text(f'''{imports}
import InitECandidate.Solver.WordToStackBound.CheckCode

-- Generated by work/agent-notes/generate-word-static.py.
namespace {NS}
open Flapjack InitECandidate.Proofs.StackAnalysis InitECandidate.Solver.WordToStackBound
set_option maxRecDepth 100000

def chunk{index} : List (Nat × Nat × WordLangProgHOL (BitVec 64)) := [{entries}]

theorem chunk{index}Safe : entriesSafe 4 chunk{index} = true := by
  change ({goal}) = true
  simp only [{facts}, decide_true, Bool.true_and]

end {NS}
#print axioms {NS}.chunk{index}Safe
''')
imports = "\n".join(f"import {NS}.Chunk{i}" for i in range(52))
entries = " ++ (".join(f"chunk{i}" for i in range(52)) + " ++ []" + ")" * 51
facts = ", ".join(f"(show chunk{i}.all (fun entry => noInstallSubprogsHOL entry.2.2 && decide (ceiling entry.2.2 ≤ 4)) = true from chunk{i}Safe)" for i in range(52))
(OUT / "Programs.lean").write_text(f'''{imports}

-- Generated by work/agent-notes/generate-word-static.py. Equality to the fixed
-- compiler umbrella code list and initial-state integration remain obligations.
namespace {NS}
open Flapjack InitECandidate.Solver.WordToStackBound
set_option maxRecDepth 100000

def wordProgram : List (Nat × Nat × WordLangProgHOL (BitVec 64)) := {entries}

theorem wordProgramSafe : entriesSafe 4 wordProgram = true := by
  simp only [entriesSafe, wordProgram, List.all_append, List.all_nil, {facts}, Bool.and_true]

theorem wordCodeSafe : CodeSafe 4 (sptFromAList wordProgram) :=
  entriesSafe_codeSafe 4 wordProgram wordProgramSafe

end {NS}
#print axioms {NS}.wordProgramSafe
#print axioms {NS}.wordCodeSafe
''')
print(f"Generated 824 procedure checks, 52 chunks and Programs under {OUT}")
